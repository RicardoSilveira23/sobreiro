use chrono::{DateTime, NaiveTime, Utc};
use sobreiro_core::display::{ClockFormat, Zone, when};

use crate::{clock, en_gb, en_us, oracle_zone, pt_pt, time};

fn now() -> DateTime<Utc> {
    time("2026-11-09T10:00:00Z")
}

fn f(t: &str, clock: &ClockFormat) -> String {
    when::format(time(t), now(), &Zone::utc(), clock)
}

#[test]
fn same_day() {
    assert_eq!(f("2026-11-09T14:20:00Z", &en_us()), "2:20 PM");
}

#[test]
fn within_six_days_gets_day_name() {
    assert_eq!(f("2026-11-14T00:00:00Z", &en_us()), "Sat 12:00 AM");
}

#[test]
fn seven_days_ahead_gets_date() {
    assert_eq!(f("2026-11-16T00:00:00Z", &en_us()), "Mon 16 Nov 12:00 AM");
}

#[test]
fn seven_days_back_gets_date() {
    assert_eq!(f("2026-11-02T14:02:00Z", &en_us()), "Mon 2 Nov 2:02 PM");
}

#[test]
fn six_days_back_gets_day_name() {
    assert_eq!(f("2026-11-03T14:02:00Z", &en_us()), "Tue 2:02 PM");
}

#[test]
fn uses_culture_time_pattern() {
    assert_eq!(f("2026-11-09T14:20:00Z", &pt_pt()), "14:20");
}

/// (a culture, its short time pattern, its words for morning and afternoon), as .NET 10 on
/// this PC gives them.
const CULTURES: &[(&str, &str, &str, &str)] = &[
    ("en-US", "h:mm tt", "AM", "PM"),
    ("en-GB", "HH:mm", "am", "pm"),
    ("pt-PT", "HH:mm", "da manh\u{e3}", "da tarde"),
    ("ko-KR", "tt h:mm", "\u{c624}\u{c804}", "\u{c624}\u{d6c4}"),
    ("fi-FI", "H.mm", "ap.", "ip."),
];

fn culture(name: &str) -> ClockFormat {
    let (_, pattern, am, pm) = CULTURES.iter().find(|row| row.0 == name).unwrap();
    clock(pattern, am, pm)
}

#[test]
fn the_helpers_hold_what_dotnet_gives() {
    assert_eq!(culture("en-US"), en_us());
    assert_eq!(culture("en-GB"), en_gb());
    assert_eq!(culture("pt-PT"), pt_pt());
}

