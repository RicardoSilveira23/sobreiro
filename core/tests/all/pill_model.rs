fn cop_now() -> DateTime<Utc> {
    time("2026-11-09T12:00:00Z")
}

fn credits() -> Limit {
    credits_seen(cop_now(), cop_now())
}

fn credits_seen(observed: DateTime<Utc>, at: DateTime<Utc>) -> Limit {
    let reading = CopilotReading {
        budget: 15000.0,
        used: 2644.0,
        resets_at: Some(time("2026-12-01T00:00:00Z")),
        observed_at: observed,
        source: CopilotSource::Live,
    };
    limit_list::from_copilot(Some(&reading), at).remove(0)
}

fn close(actual: f64, expected: f64, tolerance: f64) {
    assert!(
        (actual - expected).abs() <= tolerance,
        "{actual} vs {expected}"
    );
}

