fn now() -> DateTime<Utc> {
    time("2026-11-09T12:00:00Z")
}

fn l(kind: LimitKind, percent: f64) -> Limit {
    Limit::new(
        "Claude Code",
        kind,
        label(kind),
        percent,
        None,
        now(),
        false,
    )
}

fn label(kind: LimitKind) -> &'static str {
    match kind {
        LimitKind::Session => "Session",
        LimitKind::Weekly => "Weekly",
        LimitKind::Spend => "Spend",
        LimitKind::Credits => "Credits",
    }
}

fn line(label: &'static str, figure: &str, stale: bool) -> PillLine {
    PillLine {
        label,
        figure: figure.to_string(),
        stale,
    }
}

#[test]
fn both_windows() {
    let m = PillModel::from_limits(&[l(LimitKind::Session, 37.9), l(LimitKind::Weekly, 61.0)]);
    assert_eq!(m.session, line("5h", "37%", false));
    assert_eq!(m.weekly, line("7d", "61%", false));
}

#[test]
fn missing_windows_read_a_dash() {
    let m = PillModel::from_limits(&[]);
    assert_eq!(m.session, line("5h", "–", false));
    assert_eq!(m.weekly, line("7d", "–", false));
}

