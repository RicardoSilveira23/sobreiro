#[test]
fn one_missed_poll_marks_nothing() {
    let limits = [
        aged(LimitKind::Session, TimeDelta::hours(3)),
        aged(LimitKind::Weekly, TimeDelta::hours(3)),
        old_credits(TimeDelta::days(3)),
    ];
    let m = states(
        &limits,
        ProviderState::Offline,
        1,
        ProviderState::Offline,
        1,
    );
    assert!(!m.claude_stale);
    assert!(!m.session.stale);
    assert!(!m.weekly.stale);
    let copilot = m.copilot.unwrap();
    assert!(!copilot.stale);
    assert!(!copilot.credits.stale);
}

