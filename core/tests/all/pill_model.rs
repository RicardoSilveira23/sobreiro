#[test]
fn each_block_decides_alone() {
    let copilot_only = states(
        &[
            aged(LimitKind::Session, TimeDelta::minutes(1)),
            aged(LimitKind::Weekly, TimeDelta::minutes(1)),
            old_credits(TimeDelta::days(3)),
        ],
        ProviderState::Ok,
        0,
        ProviderState::NoSignIn,
        2,
    );
    assert!(!copilot_only.claude_stale);
    assert!(!copilot_only.session.stale);
    assert!(copilot_only.copilot.unwrap().stale);

    let claude_only = states(
        &[
            aged(LimitKind::Session, TimeDelta::hours(3)),
            aged(LimitKind::Weekly, TimeDelta::hours(3)),
            old_credits(TimeDelta::minutes(1)),
        ],
        ProviderState::Refused,
        2,
        ProviderState::Ok,
        0,
    );
    assert!(claude_only.claude_stale);
    let copilot = claude_only.copilot.unwrap();
    assert!(!copilot.stale);
    assert!(!copilot.credits.stale);
}

