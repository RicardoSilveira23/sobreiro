#[test]
fn pill_model_answers_as_the_csharp_did() {
    for &(
        limits,
        overload,
        zone,
        show_claude,
        live,
        live_misses,
        copilot,
        copilot_misses,
        now,
        expected,
    ) in ROWS
    {
        let limits = limits_of(limits);
        let zone_value = oracle_zone(zone);
        let model = match overload {
            0 => PillModel::from_limits(&limits),
            1 => PillModel::from(&limits, &zone_value, show_claude),
            _ => PillModel::from_states(
                &limits,
                &zone_value,
                show_claude,
                state_of(live),
                live_misses,
                state_of(copilot),
                copilot_misses,
                at_ticks(now),
            ),
        };
        assert_eq!(
            dump_pill(&model),
            expected,
            "{limits:?} overload {overload} {zone} claude {show_claude} {live} {live_misses} {copilot} {copilot_misses} at {now}"
        );
    }
}
