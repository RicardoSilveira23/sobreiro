fn dump_line(line: &PillLine) -> String {
    format!("{}:{}:{}", line.label, line.figure, line.stale)
}

fn dump_ring(ring: &sobreiro_core::display::rings::Ring) -> String {
    format!("{}/{:?}/{}", ring.percent, ring.level, ring.has_data)
}

fn dump_pill(m: &PillModel) -> String {
    let copilot = m.copilot.as_ref().map_or("<none>".to_string(), |c| {
        format!(
            "{}|{}|{:016x}|{:?}|{}",
            dump_line(&c.credits),
            c.reset_date,
            c.fraction.to_bits(),
            c.level,
            c.stale
        )
    });
    [
        dump_line(&m.session),
        dump_line(&m.weekly),
        format!(
            "{}+{}+{}",
            dump_ring(&m.rings.outer),
            dump_ring(&m.rings.inner),
            m.rings.has_inner
        ),
        copilot,
        m.show_claude.to_string(),
        m.claude_stale.to_string(),
    ]
    .join("\n")
}

