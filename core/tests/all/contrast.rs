//! Ported from `tests/Sobreiro.Tests/ContrastTests.cs`.
use sobreiro_core::colours::{Rgb, contrast};

fn rgb(hex: &str) -> Rgb {
    Rgb::parse(hex).unwrap()
}

#[test]
fn black_on_white_is_twenty_one() {
    let ratio = contrast::ratio(rgb("#000000"), rgb("#FFFFFF"));
    assert!((ratio - 21.0).abs() < 0.005, "{ratio}");
}

#[test]
fn grey_767676_on_white_is_454() {
    let ratio = contrast::ratio(rgb("#767676"), rgb("#FFFFFF"));
    assert!((ratio - 4.54).abs() <= 0.005, "{ratio}");
}

#[test]
fn ratio_is_symmetric() {
    let a = rgb("#7B62FF");
    let b = rgb("#0B0B0B");
    assert_eq!(contrast::ratio(a, b), contrast::ratio(b, a));
}

#[test]
fn parse_and_to_hex_round_trip_in_upper_case() {
    assert_eq!(rgb("#7b62ff").to_hex(), "#7B62FF");
}

