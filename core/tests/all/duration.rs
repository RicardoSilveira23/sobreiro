//! Ported from `tests/Sobreiro.Tests/DurationTests.cs`.
use chrono::TimeDelta;
use sobreiro_core::display::duration::format;

use crate::span;

#[test]
fn formats_minutes() {
    let rows = [
        (3 * 60 + 11, "3h 11m"),
        (3 * 1440 + 13 * 60 + 59, "3d 13h"),
        (2 * 1440 + 30, "2d"),
        (45, "45m"),
    ];
    for (minutes, expected) in rows {
        assert_eq!(format(TimeDelta::minutes(minutes)), expected);
    }
}

#[test]
fn drops_seconds_at_whole_hours() {
    assert_eq!(format(TimeDelta::hours(2) + TimeDelta::seconds(30)), "2h");
}

#[test]
fn under_a_minute() {
    assert_eq!(format(TimeDelta::seconds(30)), "under 1m");
}

#[test]
fn negative() {
    assert_eq!(format(TimeDelta::hours(-2)), "under 1m");
}

