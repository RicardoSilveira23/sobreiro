#[test]
fn fill_follows_the_level() {
    let c = TaskbarColours::for_taskbar(false, false, BarColourOption::Purple, None);
    assert_eq!(c.fill(UsageLevel::Normal), c.base);
    assert_eq!(c.fill(UsageLevel::Warning), c.warning);
    assert_eq!(c.fill(UsageLevel::Error), c.error);
}

/// `ink` at `alpha` over `ground`, as one channel. The C# rounds a half to the even number.
fn over(ink: u8, ground: u8, alpha: u8) -> u8 {
    let (ink, ground, alpha) = (f64::from(ink), f64::from(ground), f64::from(alpha));
    ((ink * alpha + ground * (255.0 - alpha)) / 255.0).round_ties_even() as u8
}

/// The arc must stand out from its track on a dark taskbar (#1C1C1C): white at a given alpha
/// over it.
fn white_over_dark(alpha: u8) -> Rgb {
    let channel = over(255, 0x1C, alpha);
    Rgb::new(channel, channel, channel)
}

#[test]
fn dark_purple_reads_on_the_dark_track() {
    let track = white_over_dark(TRACK_ALPHA);
    let c = TaskbarColours::for_taskbar(false, false, BarColourOption::Purple, None);
    assert!(contrast::ratio(c.base, track) >= 3.0);
}

/// The 16 px tray icon needs a stronger track than the pill, or it vanishes.
#[test]
fn icon_track_shows_on_the_dark_taskbar() {
    assert!(
        contrast::ratio(
            white_over_dark(ICON_TRACK_ALPHA),
            Rgb::new(0x1C, 0x1C, 0x1C)
        ) >= 2.0
    );
}

#[test]
fn dark_purple_reads_on_the_icon_track() {
    let c = TaskbarColours::for_taskbar(false, false, BarColourOption::Purple, None);
    assert!(contrast::ratio(c.base, white_over_dark(ICON_TRACK_ALPHA)) >= 2.0);
}

/// A stopped block's fill: the ink at half strength, as drawn in the chosen variant.
#[test]
fn the_stale_fill_is_the_ink_at_half_strength() {
    assert_eq!(STALE_ALPHA, 0x80);
}

#[test]
fn the_stale_fill_reads_on_the_dark_track() {
    assert!(contrast::ratio(white_over_dark(STALE_ALPHA), white_over_dark(TRACK_ALPHA)) >= 3.0);
}

/// On a light taskbar (#F0F0F0) the ink is #1A1A1A.
fn ink_over_light(alpha: u8) -> Rgb {
    let channel = over(0x1A, 0xF0, alpha);
    Rgb::new(channel, channel, channel)
}

#[test]
fn the_stale_fill_reads_on_the_light_track() {
    assert!(contrast::ratio(ink_over_light(STALE_ALPHA), ink_over_light(TRACK_ALPHA)) >= 2.0);
}

