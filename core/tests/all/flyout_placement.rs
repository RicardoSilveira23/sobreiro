//! Ported from `tests/Sobreiro.Tests/FlyoutPlacementTests.cs`. The last tests walk rows that the
//! C# of 1.x wrote out itself: first rows whose coordinates all lie within 100000 pixels of the
//! origin, so that no sum overflows, then rows at the ends of an `i32`, where both wrap.
use sobreiro_core::display::flyout_placement::{self, PixelRect, TaskbarEdge};

const MONITOR: PixelRect = rect(0, 0, 1920, 1080);
const W: i32 = 330;
const H: i32 = 400;
const M: i32 = 12;

const fn rect(left: i32, top: i32, right: i32, bottom: i32) -> PixelRect {
    PixelRect {
        left,
        top,
        right,
        bottom,
    }
}

fn run(monitor: PixelRect, work: PixelRect, cx: i32, cy: i32) -> (TaskbarEdge, i32, i32) {
    let (x, y) = flyout_placement::place(monitor, work, cx, cy, W, H, M);
    (flyout_placement::edge(monitor, work, cx, cy), x, y)
}

#[test]
fn bottom_taskbar_clamps_to_the_right() {
    assert_eq!(
        run(MONITOR, rect(0, 0, 1920, 1032), 1800, 1060),
        (TaskbarEdge::Bottom, 1578, 620)
    );
}

#[test]
fn bottom_taskbar_centres_on_the_cursor() {
    assert_eq!(run(MONITOR, rect(0, 0, 1920, 1032), 300, 1060).1, 135);
}

#[test]
fn top_taskbar() {
    assert_eq!(
        run(MONITOR, rect(0, 48, 1920, 1080), 1800, 20),
        (TaskbarEdge::Top, 1578, 60)
    );
}

#[test]
fn left_taskbar() {
    assert_eq!(
        run(MONITOR, rect(48, 0, 1920, 1080), 20, 900),
        (TaskbarEdge::Left, 60, 668)
    );
}

#[test]
fn right_taskbar() {
    assert_eq!(
        run(MONITOR, rect(0, 0, 1872, 1080), 1900, 500),
        (TaskbarEdge::Right, 1530, 300)
    );
}

#[test]
fn auto_hide_uses_the_nearest_monitor_edge() {
    let (edge, _, y) = run(MONITOR, MONITOR, 1800, 1075);
    assert_eq!(edge, TaskbarEdge::Bottom);
    assert_eq!(y, 668);
}

#[test]
fn second_monitor_on_the_left() {
    assert_eq!(
        run(rect(-1920, 0, 0, 1080), rect(-1920, 0, 0, 1032), -100, 1060).1,
        -342
    );
}

#[test]
fn rect_sizes() {
    let r = rect(10, 20, 110, 70);
    assert_eq!(r.width(), 100);
    assert_eq!(r.height(), 50);
}

fn edge_of(name: &str) -> TaskbarEdge {
    match name {
        "Bottom" => TaskbarEdge::Bottom,
        "Top" => TaskbarEdge::Top,
        "Left" => TaskbarEdge::Left,
        "Right" => TaskbarEdge::Right,
        _ => panic!("no edge named {name}"),
    }
}

