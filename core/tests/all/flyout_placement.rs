#[test]
fn flyout_placement_at_the_ends_of_an_int_answers_as_the_csharp_did() {
    for &(monitor, work, cx, cy, w, h, m, edge, x, y) in EXTREME_ROWS {
        let rect = |(left, top, right, bottom): Rect| rect(left, top, right, bottom);
        let (monitor, work) = (rect(monitor), rect(work));
        assert_eq!(
            flyout_placement::edge(monitor, work, cx, cy),
            edge_of(edge),
            "{monitor:?} {work:?} cursor {cx} {cy}"
        );
        assert_eq!(
            flyout_placement::place(monitor, work, cx, cy, w, h, m),
            (x, y),
            "{monitor:?} {work:?} cursor {cx} {cy} size {w} {h} margin {m}"
        );
    }
}
