#[test]
fn edge_and_place_answer_as_the_csharp_did() {
    for (monitor, work, cx, cy, w, h, margin, edge, x, y) in ROWS {
        let (monitor, work) = (to_rect(*monitor), to_rect(*work));
        let row = format!("{monitor:?} {work:?} cursor {cx},{cy} flyout {w}x{h} margin {margin}");
        assert_eq!(
            flyout_placement::edge(monitor, work, *cx, *cy),
            edge_of(edge),
            "{row}"
        );
        assert_eq!(
            flyout_placement::place(monitor, work, *cx, *cy, *w, *h, *margin),
            (*x, *y),
            "{row}"
        );
    }
}

