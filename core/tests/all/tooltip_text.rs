fn now() -> DateTime<Utc> {
    time("2026-11-09T12:00:00Z")
}

fn observed() -> DateTime<Utc> {
    time("2026-11-09T11:58:00Z")
}

fn render_with(limits: Option<RateLimits>, clock: &ClockFormat) -> String {
    let list = match limits {
        None => Vec::new(),
        Some(limits) => limit_list::from(
            Some(&UsageSnapshot {
                limits,
                observed_at: observed(),
            }),
            now(),
        ),
    };
    tooltip_text::render(&list, now(), &Zone::utc(), clock, false)
}

fn render(limits: Option<RateLimits>) -> String {
    render_with(limits, &en_us())
}

fn limits(
    five_hour: Option<LimitWindow>,
    seven_day: Option<LimitWindow>,
    spend: Option<SpendLimit>,
) -> RateLimits {
    RateLimits {
        five_hour,
        seven_day,
        spend,
    }
}

#[test]
fn no_limits() {
    assert_eq!(render(None), "Sobreiro · no data yet");
}

#[test]
fn session_and_weekly() {
    assert_eq!(
        render(Some(limits(
            Some(window(8.0, Some(time("2026-11-09T14:20:00Z")))),
            Some(window(44.0, Some(time("2026-11-14T00:00:00Z")))),
            None
        ))),
        "Session 8% · resets 2:20 PM\nWeekly 44% · resets Sat 12:00 AM\nas of 11:58 AM"
    );
}

#[test]
fn absent_session_shows_dash() {
    let text = render(Some(limits(
        None,
        Some(window(44.0, Some(time("2026-11-14T00:00:00Z")))),
        None,
    )));
    assert!(text.starts_with("Session –\n"), "{text}");
}

#[test]
fn reset_session() {
    let text = render(Some(limits(
        Some(window(30.0, Some(time("2026-11-09T11:00:00Z")))),
        None,
        None,
    )));
    assert!(text.starts_with("Session 0% · reset 11:00 AM\n"), "{text}");
}

fn full_limits() -> RateLimits {
    limits(
        Some(window(8.0, Some(time("2026-11-09T14:20:00Z")))),
        Some(window(44.0, Some(time("2026-11-14T00:00:00Z")))),
        Some(spend(
            62.8,
            Some(time("2026-11-16T00:00:00Z")),
            None,
            None,
            None,
        )),
    )
}

#[test]
fn spend_line_comes_before_as_of() {
    assert_eq!(
        render(Some(full_limits())),
        "Session 8% · resets 2:20 PM\nWeekly 44% · resets Sat 12:00 AM\nSpend 62% · resets Mon 16 Nov 12:00 AM\nas of 11:58 AM"
    );
}

#[test]
fn limit_without_reset_time_shows_only_percentage() {
    let text = render(Some(limits(Some(window(8.0, None)), None, None)));
    assert!(text.starts_with("Session 8%\n"), "{text}");
}

// The C# pattern also holds `zzz`, the offset, which a `ClockFormat` has no letter for: it is
// written out as the UTC offset it gives here.
#[test]
fn long_culture_pattern_is_truncated() {
    let long = clock(
        "HH:mm:ss 'oclock' +00:00 'and then some more words to make it long'",
        "AM",
        "PM",
    );
    let text = render_with(Some(full_limits()), &long);
    assert_eq!(text.encode_utf16().count(), MAX_LENGTH);
}

fn cop_now() -> DateTime<Utc> {
    time("2026-11-09T12:00:00Z")
}

fn credits_at(used: f64, observed: DateTime<Utc>) -> Limit {
    let reading = CopilotReading {
        budget: 15000.0,
        used,
        resets_at: Some(time("2026-12-01T00:00:00Z")),
        observed_at: observed,
        source: CopilotSource::Live,
    };
    limit_list::from_copilot(Some(&reading), cop_now()).remove(0)
}

#[test]
fn claude_tooltip_ignores_copilot() {
    let claude = Limit::new(
        providers::CLAUDE,
        LimitKind::Session,
        "Session",
        8.0,
        None,
        observed(),
        false,
    );
    let text = tooltip_text::render(
        &[credits_at(2644.0, cop_now()), claude],
        now(),
        &Zone::utc(),
        &en_us(),
        false,
    );
    assert!(!text.contains("AI credits"), "{text}");
    assert!(text.ends_with("as of 11:58 AM"), "{text}");
}

#[test]
fn copilot_tooltip_has_three_lines() {
    let text = tooltip_text::render_copilot(
        &credits_at(2644.0, observed()),
        now(),
        &Zone::utc(),
        &en_us(),
    );
    assert_eq!(
        text,
        "AI credits 17% · resets Tue 1 Dec 12:00 AM\n2,644 of 15,000 credits\nas of 11:58 AM"
    );
    assert!(text.encode_utf16().count() <= MAX_LENGTH);
}

#[test]
fn tooltip_asks_to_reconnect_when_there_is_no_data_on_a_legacy_connection() {
    let text = tooltip_text::render(&[], now(), &Zone::utc(), &en_us(), true);
    assert_eq!(
        text,
        "Sobreiro · no data yet\nStill on the old bridge: reconnect from the tray menu."
    );
    assert!(text.encode_utf16().count() <= MAX_LENGTH);
    assert_eq!(
        tooltip_text::render(&[], now(), &Zone::utc(), &en_us(), false),
        "Sobreiro · no data yet"
    );
}

