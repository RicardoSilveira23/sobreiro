#[test]
fn the_pace_setting_reaches_the_bar_and_the_badge() {
    let at = time("2026-11-12T09:00:00Z");
    let weekly = Limit {
        window: Some(TimeDelta::days(7)),
        ..Limit::new(
            providers::CLAUDE,
            LimitKind::Weekly,
            "Weekly",
            58.0,
            Some(time("2026-11-16T09:00:00Z")),
            at,
            false,
        )
    };
    let model = |days| {
        let options = FlyoutOptions {
            days,
            ..FlyoutOptions::default()
        };
        FlyoutModel::from(
            std::slice::from_ref(&weekly),
            at,
            &Zone::utc(),
            &en_us(),
            &options,
        )
        .weekly
    };
    let every_day = model(PaceDays::EveryDay);
    let weekdays = model(PaceDays::Weekdays);
    assert_eq!(every_day.projected_fraction, Some(1.0));
    assert_eq!(every_day.status.unwrap().kind, StatusKind::Ends);
    close(weekdays.projected_fraction.unwrap(), 0.9667, 0.0001);
    assert_eq!(weekdays.status.unwrap().kind, StatusKind::OnTrack);
}

