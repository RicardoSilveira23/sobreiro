#[test]
fn figures_that_are_not_finite_answer_as_the_csharp_did() {
    for &(used, cap, period, expected) in ODD_MONEY {
        let row: LimitRow = (
            2,
            10.0,
            NONE,
            0,
            false,
            NONE,
            Some(used),
            cap,
            period,
            None,
            None,
        );
        let model = FlyoutModel::from(
            &[limit_of(&row)],
            at_ticks(0),
            &Zone::utc(),
            &en_us(),
            &FlyoutOptions::default(),
        );
        let detail = or_none(&model.spend.unwrap().detail);
        assert_eq!(detail, expected, "used {used:?} cap {cap:?}");
    }

    const HOUR: i64 = 36_000_000_000;
    for &(kind, percent, days, expected) in ODD_VIEWS {
        let (window, usd, credits) = match kind {
            0 => (5 * HOUR, None, None),
            2 => (30 * 24 * HOUR, Some(percent), None),
            _ => (30 * 24 * HOUR, None, Some(percent)),
        };
        let row: LimitRow = (
            kind,
            percent,
            3 * HOUR,
            0,
            false,
            window,
            usd,
            usd,
            if kind == 2 { "monthly" } else { "" },
            credits,
            credits,
        );
        let options = FlyoutOptions {
            days: if days == "weekdays" {
                PaceDays::Weekdays
            } else {
                PaceDays::EveryDay
            },
            ..FlyoutOptions::default()
        };
        let model = FlyoutModel::from(
            &[limit_of(&row)],
            at_ticks(0),
            &Zone::utc(),
            &en_us(),
            &options,
        );
        let view = match kind {
            0 => model.session,
            2 => model.spend.unwrap(),
            _ => model.copilot.unwrap().credits,
        };
        let actual = dump_view(&view)
            .replace("7ff8000000000000", "nan")
            .replace("fff8000000000000", "nan");
        assert_eq!(actual, expected, "kind {kind} percent {percent:?} {days}");
    }
}
