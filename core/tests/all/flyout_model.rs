fn now() -> DateTime<Utc> {
    time("2026-11-09T10:00:00Z")
}

fn build_at(limits: Option<RateLimits>, observed: DateTime<Utc>) -> FlyoutModel {
    let list = match limits {
        None => Vec::new(),
        Some(limits) => limit_list::from(
            Some(&UsageSnapshot {
                limits,
                observed_at: observed,
            }),
            now(),
        ),
    };
    FlyoutModel::from(
        &list,
        now(),
        &Zone::utc(),
        &en_us(),
        &FlyoutOptions::default(),
    )
}

fn build(limits: Option<RateLimits>) -> FlyoutModel {
    build_at(limits, now())
}

fn limits(
    five_hour: Option<sobreiro_core::usage::LimitWindow>,
    seven_day: Option<sobreiro_core::usage::LimitWindow>,
    spend: Option<sobreiro_core::usage::SpendLimit>,
) -> RateLimits {
    RateLimits {
        five_hour,
        seven_day,
        spend,
    }
}

fn mockup() -> RateLimits {
    limits(
        Some(window(27.0, Some(now() + TimeDelta::minutes(191)))),
        Some(window(74.0, Some(now() + TimeDelta::hours(85)))),
        None,
    )
}

fn close(actual: f64, expected: f64, tolerance: f64) {
    assert!(
        (actual - expected).abs() <= tolerance,
        "{actual} vs {expected}"
    );
}

#[test]
fn mockup_session() {
    let s = build(Some(mockup())).session;
    assert_eq!(s.label, "Session");
    assert_eq!(s.used_figure, "27%");
    assert_eq!(s.left_figure, "73%");
    assert_eq!(s.resets_in.as_deref(), Some("resets in 3h 11m"));
    assert_eq!(
        s.status,
        Some(LimitStatus {
            kind: StatusKind::OnTrack,
            text: "On track".to_string()
        })
    );
    close(s.projected_fraction.unwrap(), 0.7431, 0.0001);
    assert_eq!(s.level, UsageLevel::Normal);
}

