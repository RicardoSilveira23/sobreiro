#[test]
fn flyout_model_from_answers_as_the_csharp_did() {
    for (limits, now, zone, clock, live, legacy, show_claude, note, days, expected) in FLYOUT {
        let options = FlyoutOptions {
            live: state_of(live),
            legacy_connection: *legacy,
            copilot_note: note.map(str::to_string),
            show_claude: *show_claude,
            days: if *days == "weekdays" {
                PaceDays::Weekdays
            } else {
                PaceDays::EveryDay
            },
        };
        let model = FlyoutModel::from(
            &crate::limits_of(limits),
            at_ticks(*now),
            &oracle_zone(zone),
            &oracle_clock(clock),
            &options,
        );
        assert_eq!(
            dump_model(&model),
            *expected,
            "{limits:?} at {now} {zone} {clock} {live} legacy {legacy} claude {show_claude} {note:?} {days}"
        );
    }
}

