fn or_none(text: &Option<String>) -> String {
    text.clone().unwrap_or_else(|| "<none>".to_string())
}

fn dump_view(v: &LimitView) -> String {
    let projected = v
        .projected_fraction
        .map_or("<none>".to_string(), |p| format!("{:016x}", p.to_bits()));
    let status = v
        .status
        .as_ref()
        .map_or("<none>".to_string(), |s| format!("{:?}:{}", s.kind, s.text));
    format!(
        "{:?}|{}|{}|{}|{}|{:016x}|{}|{:?}|{}|{}|{}",
        v.kind,
        v.label,
        v.has_data,
        v.used_figure,
        v.left_figure,
        v.used_fraction.to_bits(),
        projected,
        v.level,
        status,
        or_none(&v.resets_in),
        or_none(&v.detail)
    )
}

fn dump_model(m: &FlyoutModel) -> String {
    let spend = m.spend.as_ref().map_or("<none>".to_string(), dump_view);
    let copilot = m.copilot.as_ref().map_or("<none>".to_string(), |c| {
        format!("{}|note={}", dump_view(&c.credits), or_none(&c.note))
    });
    [
        m.title.to_string(),
        dump_view(&m.session),
        dump_view(&m.weekly),
        spend,
        m.footer.clone(),
        copilot,
        m.show_claude.to_string(),
    ]
    .join("\n")
}

