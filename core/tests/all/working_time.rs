use chrono::TimeDelta;
use sobreiro_core::display::{Zone, working_time};

use crate::{east, oracle_zone, span, time};

// 2026-11-09 is a Monday.

#[test]
fn weekdays_count_in_full() {
    assert_eq!(
        working_time::between(
            time("2026-11-09T09:00:00Z"),
            time("2026-11-12T09:00:00Z"),
            &Zone::utc()
        ),
        TimeDelta::hours(72)
    );
}

#[test]
fn a_weekend_in_the_middle_is_skipped() {
    assert_eq!(
        working_time::between(
            time("2026-11-06T18:00:00Z"),
            time("2026-11-09T09:00:00Z"),
            &Zone::utc()
        ),
        TimeDelta::hours(15)
    );
}

#[test]
fn inside_a_weekend_is_zero() {
    assert_eq!(
        working_time::between(
            time("2026-11-07T12:00:00Z"),
            time("2026-11-08T12:00:00Z"),
            &Zone::utc()
        ),
        TimeDelta::zero()
    );
}

#[test]
fn backwards_is_zero() {
    assert_eq!(
        working_time::between(
            time("2026-11-10T00:00:00Z"),
            time("2026-11-09T00:00:00Z"),
            &Zone::utc()
        ),
        TimeDelta::zero()
    );
}

#[test]
fn a_whole_november_has_21_weekdays() {
    assert_eq!(
        working_time::between(
            time("2026-11-01T00:00:00Z"),
            time("2026-12-01T00:00:00Z"),
            &Zone::utc()
        ),
        TimeDelta::hours(504)
    );
}

#[test]
fn the_day_of_the_week_is_the_local_one() {
    let plus_nine = Zone::fixed(east(9 * 3600));
    // Fri 22:00Z to Sat 02:00Z is Sat 07:00 to Sat 11:00 at +09:00.
    assert_eq!(
        working_time::between(
            time("2026-11-06T22:00:00Z"),
            time("2026-11-07T02:00:00Z"),
            &plus_nine
        ),
        TimeDelta::zero()
    );
    // Sun 20:00Z to Sun 23:00Z is Mon 05:00 to Mon 08:00 at +09:00.
    assert_eq!(
        working_time::between(
            time("2026-11-08T20:00:00Z"),
            time("2026-11-08T23:00:00Z"),
            &plus_nine
        ),
        TimeDelta::hours(3)
    );
}

#[test]
fn a_clock_change_at_the_weekend_moves_midnight() {
    // Lisbon goes from +01:00 to +00:00 on Sunday 2026-10-25.
    let lisbon = oracle_zone("Europe/Lisbon");
    let fri_noon = time("2026-10-23T11:00:00Z"); // 12:00 local
    let mon_noon = time("2026-10-26T12:00:00Z"); // 12:00 local
    assert_eq!(
        working_time::between(fri_noon, mon_noon, &lisbon),
        TimeDelta::hours(24)
    );
    assert_eq!(
        working_time::after(fri_noon, TimeDelta::hours(24), &lisbon),
        mon_noon
    );
}

#[test]
fn after_skips_the_weekend() {
    assert_eq!(
        working_time::after(
            time("2026-11-06T00:00:00Z"),
            TimeDelta::hours(52),
            &Zone::utc()
        ),
        time("2026-11-10T04:00:00Z")
    );
}

#[test]
fn after_from_a_saturday_starts_on_monday() {
    assert_eq!(
        working_time::after(
            time("2026-11-07T12:00:00Z"),
            TimeDelta::hours(1),
            &Zone::utc()
        ),
        time("2026-11-09T01:00:00Z")
    );
}

#[test]
fn after_nothing_is_the_start() {
    assert_eq!(
        working_time::after(
            time("2026-11-07T12:00:00Z"),
            TimeDelta::zero(),
            &Zone::utc()
        ),
        time("2026-11-07T12:00:00Z")
    );
}

