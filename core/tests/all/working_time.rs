#[test]
fn after_a_span_of_any_length_ends_at_the_last_moment_at_once() {
    use chrono::{DateTime, Utc};
    use sobreiro_core::display::{PaceDays, limit_status, when};
    use sobreiro_core::limits::{Limit, LimitKind};

    let started = std::time::Instant::now();
    for zone in [
        Zone::utc(),
        Zone::fixed(east(3600)),
        Zone::fixed(east(-12 * 3600)),
    ] {
        for from in [
            time("2026-11-09T09:00:00Z"),
            time("2026-11-14T09:00:00Z"),
            DateTime::<Utc>::MAX_UTC,
        ] {
            assert_eq!(
                working_time::after(from, TimeDelta::MAX, &zone),
                DateTime::<Utc>::MAX_UTC
            );
        }
        // A span that is longer than all the time that is left, but far from the largest.
        assert_eq!(
            working_time::after(
                time("2026-11-09T09:00:00Z"),
                TimeDelta::days(100_000_000),
                &zone
            ),
            DateTime::<Utc>::MAX_UTC
        );
        // Near the last moment the answer stops at it, and does not overflow.
        let near_end = DateTime::<Utc>::MAX_UTC - TimeDelta::hours(2);
        let _ = working_time::after(near_end, TimeDelta::hours(1), &zone);
        let _ = working_time::after(near_end, TimeDelta::hours(3), &zone);
    }
    assert!(started.elapsed() < std::time::Duration::from_secs(5));

    // The last moment can be written, in any zone and in a status.
    for zone in [
        Zone::utc(),
        Zone::fixed(east(3600)),
        Zone::fixed(east(-3600)),
    ] {
        let text = when::format(
            DateTime::<Utc>::MAX_UTC,
            time("2026-11-09T09:00:00Z"),
            &zone,
            &crate::en_us(),
        );
        assert!(!text.is_empty());
        let mut limit = Limit::new(
            "Claude Code",
            LimitKind::Weekly,
            "Weekly",
            6.0,
            Some(DateTime::<Utc>::MAX_UTC),
            DateTime::<Utc>::MAX_UTC - TimeDelta::days(1),
            false,
        );
        limit.window = Some(TimeDelta::days(14));
        let status = limit_status::for_limit(
            &limit,
            time("2026-11-09T09:00:00Z"),
            &zone,
            &crate::en_us(),
            PaceDays::Weekdays,
        );
        assert!(status.is_some());
    }
}
