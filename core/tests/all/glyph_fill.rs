//! Ported from `tests/Sobreiro.Tests/GlyphFillTests.cs`. The last test walks rows that the C#
//! of 1.x wrote out itself.
use sobreiro_core::display::flyout_model::LimitView;
use sobreiro_core::display::glyph_fill::GlyphFill;
use sobreiro_core::limits::{LimitKind, UsageLevel};

fn view(used: f64, projected: Option<f64>, has_data: bool) -> LimitView {
    LimitView {
        kind: LimitKind::Session,
        label: "Session",
        has_data,
        used_figure: String::new(),
        left_figure: String::new(),
        used_fraction: used,
        projected_fraction: projected,
        level: UsageLevel::Normal,
        status: None,
        resets_in: None,
        detail: None,
    }
}

fn nothing() -> GlyphFill {
    GlyphFill {
        left_cells: 0,
        soon_cells: 0,
        left_percent: 0.0,
        soon_percent: 0.0,
    }
}

fn close(actual: f64, expected: f64) {
    assert!(
        (actual - expected).abs() <= 0.0001,
        "{actual} vs {expected}"
    );
}

#[test]
fn mockup_session_has_seven_left_and_five_soon() {
    let fill = GlyphFill::from(&view(0.27, Some(0.7431), true));
    assert_eq!(fill.left_cells, 7);
    assert_eq!(fill.soon_cells, 5);
    close(fill.left_percent, 73.0);
    close(fill.soon_percent, 47.31);
}

#[test]
fn mockup_weekly_has_three_left_all_soon() {
    let fill = GlyphFill::from(&view(0.74, Some(1.0), true));
    assert_eq!(fill.left_cells, 3);
    assert_eq!(fill.soon_cells, 3);
    close(fill.left_percent, 26.0);
    close(fill.soon_percent, 26.0);
}

#[test]
fn no_projection_has_nothing_soon() {
    let fill = GlyphFill::from(&view(0.27, None, true));
    assert_eq!(fill.left_cells, 7);
    assert_eq!(fill.soon_cells, 0);
    assert_eq!(fill.soon_percent, 0.0);
}

#[test]
fn full_use_has_nothing_left() {
    assert_eq!(GlyphFill::from(&view(1.0, None, true)), nothing());
}

#[test]
fn no_data_has_nothing_left() {
    assert_eq!(GlyphFill::from(&view(0.0, None, false)), nothing());
}

