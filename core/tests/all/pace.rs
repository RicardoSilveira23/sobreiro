fn now() -> DateTime<Utc> {
    time("2026-11-09T10:00:00Z")
}

fn make(
    percent: f64,
    window: Option<TimeDelta>,
    resets_in: Option<TimeDelta>,
    observed: Option<DateTime<Utc>>,
    is_reset: bool,
) -> Limit {
    let mut limit = Limit::new(
        "Claude Code",
        LimitKind::Session,
        "Session",
        percent,
        resets_in.map(|resets_in| now() + resets_in),
        observed.unwrap_or_else(now),
        is_reset,
    );
    limit.window = window;
    limit
}

fn project(limit: &Limit) -> Option<PaceProjection> {
    pace::project(limit, PaceDays::EveryDay, &Zone::utc())
}

/// Like `Assert.Equal(expected, actual, precision)`: equal to within `tolerance`.
fn near(expected: f64, actual: f64, tolerance: f64) {
    assert!(
        (expected - actual).abs() <= tolerance,
        "{actual} is not {expected} within {tolerance}"
    );
}

fn hours(span: TimeDelta) -> f64 {
    span.num_milliseconds() as f64 / 3_600_000.0
}

#[test]
fn session_on_track() {
    let p = project(&make(
        27.0,
        Some(TimeDelta::hours(5)),
        Some(TimeDelta::minutes(191)),
        None,
        false,
    ))
    .unwrap();
    near(74.31, p.projected_percent, 0.01);
    assert_eq!(p.runs_out_before_reset, None);
    assert_eq!(p.runs_out_at, None);
}

#[test]
fn weekly_runs_out() {
    let p = project(&make(
        74.0,
        Some(TimeDelta::days(7)),
        Some(TimeDelta::hours(85)),
        None,
        false,
    ))
    .unwrap();
    near(149.78, p.projected_percent, 0.01);
    let before = p.runs_out_before_reset.unwrap();
    near(55.84, hours(before), 1.0 / 60.0);
    assert_eq!(p.runs_out_at, Some(now() + TimeDelta::hours(85) - before));
}

