#[test]
fn project_answers_as_the_csharp_did() {
    for (zone, days, percent, window, resets, observed, is_reset, expected) in ROWS {
        let days = match *days {
            "every" => PaceDays::EveryDay,
            _ => PaceDays::Weekdays,
        };
        let mut limit = Limit::new(
            "Claude Code",
            LimitKind::Weekly,
            "Weekly",
            *percent,
            maybe_at(*resets),
            at_ticks(*observed),
            *is_reset,
        );
        limit.window = (*window != NONE).then(|| span(*window));
        let row = format!(
            "{zone} {days:?} {percent}% window {window} resets {resets} observed {observed} reset {is_reset}"
        );
        let actual = pace::project(&limit, days, &oracle_zone(zone));
        match (actual, expected) {
            (None, None) => {}
            (Some(actual), Some((bits, before, at))) => {
                assert_eq!(actual.projected_percent.to_bits(), *bits, "{row}");
                assert_eq!(
                    actual.runs_out_before_reset,
                    (*before != NONE).then(|| span(*before)),
                    "{row}"
                );
                assert_eq!(actual.runs_out_at, maybe_at(*at), "{row}");
            }
            (actual, expected) => panic!("{row}: {actual:?}, the C# gave {expected:?}"),
        }
    }
}

#[test]
fn the_rows_hold_both_answers_and_both_days() {
    assert!(ROWS.iter().any(|row| row.7.is_none()));
    assert!(
        ROWS.iter()
            .any(|row| matches!(row.7, Some((_, before, _)) if before != NONE))
    );
    assert!(ROWS.iter().any(|row| row.1 == "weekdays"));
}
