fn long(percent: f64, resets: &str, observed: &str, window_days: i64) -> Limit {
    let mut limit = Limit::new(
        "Claude Code",
        LimitKind::Weekly,
        "Weekly",
        percent,
        Some(time(resets)),
        time(observed),
        false,
    );
    limit.window = Some(TimeDelta::days(window_days));
    limit
}

fn weekly(percent: f64, resets: &str, observed: &str) -> Limit {
    long(percent, resets, observed, 7)
}

fn weekdays(limit: &Limit) -> Option<PaceProjection> {
    pace::project(limit, PaceDays::Weekdays, &Zone::utc())
}

/// Run-out times come from a multiplication, so compare to the second.
fn near_moment(expected: &str, actual: Option<DateTime<Utc>>) {
    let expected = time(expected);
    let actual = actual.unwrap();
    assert!(
        (actual - expected).abs() < TimeDelta::seconds(1),
        "{actual} is not {expected}"
    );
}

#[test]
fn weekdays_remove_the_midweek_false_alarm() {
    // Reset Mon 09:00, read Thu 09:00 at 58%: 72 h of 168 h, or 72 h of 120 h.
    let l = weekly(58.0, "2026-11-16T09:00:00Z", "2026-11-12T09:00:00Z");
    near(135.33, project(&l).unwrap().projected_percent, 0.01);
    let p = weekdays(&l).unwrap();
    near(96.67, p.projected_percent, 0.01);
    assert_eq!(p.runs_out_at, None);
    assert_eq!(p.runs_out_before_reset, None);
}

#[test]
fn weekdays_remove_the_false_calm_after_a_weekend() {
    // Reset Fri 09:00, read Mon 09:00 at 30%: 72 h of 168 h, or 24 h of 120 h.
    let l = weekly(30.0, "2026-11-13T09:00:00Z", "2026-11-09T09:00:00Z");
    near(70.0, project(&l).unwrap().projected_percent, 0.01);
    let p = weekdays(&l).unwrap();
    near(150.0, p.projected_percent, 0.01);
    // 56 weekday hours on.
    near_moment("2026-11-11T17:00:00Z", p.runs_out_at);
    near(40.0, hours(p.runs_out_before_reset.unwrap()), 0.001);
}

#[test]
fn a_run_out_never_lands_on_the_weekend() {
    // Window Wed to Wed, read Fri 00:00 at 48%: 52 weekday hours left, past the weekend.
    let p = weekdays(&weekly(
        48.0,
        "2026-11-11T00:00:00Z",
        "2026-11-06T00:00:00Z",
    ))
    .unwrap();
    near(120.0, p.projected_percent, 0.01);
    near_moment("2026-11-10T04:00:00Z", p.runs_out_at);
    near(20.0, hours(p.runs_out_before_reset.unwrap()), 0.001);
}

#[test]
fn use_on_a_day_off_makes_it_stricter() {
    let saturday = weekdays(&weekly(
        70.0,
        "2026-11-11T00:00:00Z",
        "2026-11-07T12:00:00Z",
    ))
    .unwrap();
    let sunday = weekdays(&weekly(
        75.0,
        "2026-11-11T00:00:00Z",
        "2026-11-08T12:00:00Z",
    ))
    .unwrap();
    near(116.67, saturday.projected_percent, 0.01);
    near(125.0, sunday.projected_percent, 0.01);
    assert!(saturday.runs_out_at.unwrap() >= time("2026-11-09T00:00:00Z"));
}

#[test]
fn with_only_the_weekend_left_the_projection_is_the_current_figure() {
    let l = weekly(80.0, "2026-11-16T00:00:00Z", "2026-11-14T10:00:00Z");
    assert!(project(&l).unwrap().projected_percent > 100.0);
    let p = weekdays(&l).unwrap();
    near(80.0, p.projected_percent, 0.01);
    assert_eq!(p.runs_out_at, None);
}

#[test]
fn after_a_weekend_reset_it_is_too_early_until_five_percent_of_weekday_time() {
    // Sunday: none gone.
    assert_eq!(
        weekdays(&weekly(3.0, "2026-11-14T00:00:00Z", "2026-11-08T12:00:00Z")),
        None
    );
    // 5 h of 120 h.
    assert_eq!(
        weekdays(&weekly(3.0, "2026-11-14T00:00:00Z", "2026-11-09T05:00:00Z")),
        None
    );
    near(
        51.43,
        weekdays(&weekly(3.0, "2026-11-14T00:00:00Z", "2026-11-09T07:00:00Z"))
            .unwrap()
            .projected_percent,
        0.01,
    );
}

#[test]
fn a_month_counts_its_weekdays() {
    // November 2026, read Mon 16th 00:00 at 40%: 15 of 30 days, or 10 of 21 weekdays.
    let l = long(40.0, "2026-12-01T00:00:00Z", "2026-11-16T00:00:00Z", 30);
    near(80.0, project(&l).unwrap().projected_percent, 0.01);
    near(84.0, weekdays(&l).unwrap().projected_percent, 0.01);
}

#[test]
fn a_window_of_a_day_or_less_keeps_calendar_time() {
    // A Saturday: a session, then a daily limit.
    let mut session = Limit::new(
        "Claude Code",
        LimitKind::Session,
        "Session",
        27.0,
        Some(time("2026-11-07T13:11:00Z")),
        time("2026-11-07T10:00:00Z"),
        false,
    );
    session.window = Some(TimeDelta::hours(5));
    near(74.31, weekdays(&session).unwrap().projected_percent, 0.01);
    let daily = long(40.0, "2026-11-08T00:00:00Z", "2026-11-07T12:00:00Z", 1);
    near(80.0, weekdays(&daily).unwrap().projected_percent, 0.01);
}

