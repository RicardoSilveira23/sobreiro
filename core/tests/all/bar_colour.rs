#[test]
fn night_palettes_answer_as_the_csharp_did() {
    // Whether the palette is the dark one, and its ground, ink, soft ink, line, track, warning,
    // error and purple.
    let rows: &[(bool, [[u8; 3]; 8])] = &[
        (
            true,
            [
                [11, 11, 11],
                [244, 244, 244],
                [141, 141, 141],
                [38, 38, 38],
                [38, 38, 38],
                [255, 176, 32],
                [255, 107, 107],
                [165, 148, 255],
            ],
        ),
        (
            false,
            [
                [255, 255, 255],
                [13, 13, 13],
                [118, 118, 118],
                [228, 228, 228],
                [228, 228, 228],
                [163, 95, 0],
                [196, 38, 46],
                [90, 61, 209],
            ],
        ),
    ];
    for &(dark, expected) in rows {
        let n = NightPalette::for_dark(dark);
        let got = [
            n.ground, n.ink, n.soft, n.line, n.track, n.warning, n.error, n.purple,
        ]
        .map(|c| [c.r, c.g, c.b]);
        assert_eq!(got, expected, "dark={dark}");
        assert_eq!(n.is_dark, dark);
    }
}
