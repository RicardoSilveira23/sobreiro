// The rows below were written out by the C# of 1.x, run on 2026-11-15 on made-up palettes and
// turned into Rust by a script, not typed.

/// A palette as such a row holds it: seven colours, Light3 to Dark3.
type Quads = [[u8; 3]; 7];

/// The palette of such a row, or none.
pub fn palette_of(quads: Option<Quads>) -> Option<AccentPalette> {
    let [light3, light2, light1, accent, dark1, dark2, dark3] =
        quads?.map(|[r, g, b]| Rgb::new(r, g, b));
    Some(AccentPalette {
        light3,
        light2,
        light1,
        accent,
        dark1,
        dark2,
        dark3,
    })
}

fn source_of(name: &str) -> BarColourSource {
    match name {
        "Purple" => BarColourSource::Purple,
        "Accent" => BarColourSource::Accent,
        "AccentShade" => BarColourSource::AccentShade,
        "PurpleFallback" => BarColourSource::PurpleFallback,
        other => panic!("no source called {other}"),
    }
}

fn kind_of(name: &str) -> StatusKind {
    match name {
        "OnTrack" => StatusKind::OnTrack,
        "Ends" => StatusKind::Ends,
        "UsedUp" => StatusKind::UsedUp,
        "NotUsedYet" => StatusKind::NotUsedYet,
        "TooEarly" => StatusKind::TooEarly,
        "Resetting" => StatusKind::Resetting,
        other => panic!("no kind called {other}"),
    }
}

fn level_of(name: &str) -> UsageLevel {
    match name {
        "Normal" => UsageLevel::Normal,
        "Warning" => UsageLevel::Warning,
        "Error" => UsageLevel::Error,
        other => panic!("no level called {other}"),
    }
}

pub fn rgb_of([r, g, b]: [u8; 3]) -> Rgb {
    Rgb::new(r, g, b)
}

