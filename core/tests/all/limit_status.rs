#[test]
fn for_limit_answers_as_the_csharp_did() {
    for (zone, culture, days, now, percent, window, resets, observed, is_reset, expected) in ROWS {
        let clock = match *culture {
            "en-US" => en_us(),
            _ => en_gb(),
        };
        let days = match *days {
            "every" => PaceDays::EveryDay,
            _ => PaceDays::Weekdays,
        };
        let mut limit = Limit::new(
            "Claude Code",
            LimitKind::Weekly,
            "Weekly",
            *percent,
            maybe_at(*resets),
            at_ticks(*observed),
            *is_reset,
        );
        limit.window = (*window != NONE).then(|| span(*window));
        let actual =
            limit_status::for_limit(&limit, at_ticks(*now), &oracle_zone(zone), &clock, days)
                .map(|status| (format!("{:?}", status.kind), status.text));
        let expected = expected.map(|(kind, text)| (kind.to_string(), text.to_string()));
        assert_eq!(
            actual, expected,
            "{zone} {culture} {days:?} at {now}: {percent}% window {window} resets {resets} observed {observed} reset {is_reset}"
        );
    }
}

#[test]
fn the_rows_hold_every_kind_of_badge_and_none() {
    for kind in [
        "OnTrack",
        "Ends",
        "UsedUp",
        "NotUsedYet",
        "TooEarly",
        "Resetting",
    ] {
        assert!(
            ROWS.iter()
                .any(|row| row.9.is_some_and(|answer| answer.0 == kind)),
            "{kind}"
        );
    }
    assert!(ROWS.iter().any(|row| row.9.is_none()));
    assert!(
        ROWS.iter()
            .any(|row| row.9.is_some_and(|answer| answer.1 == "Likely used up"))
    );
}
