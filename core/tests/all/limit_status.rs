fn now() -> DateTime<Utc> {
    time("2026-11-09T10:00:00Z")
}

fn five() -> TimeDelta {
    TimeDelta::hours(5)
}

fn make(
    percent: f64,
    window: Option<TimeDelta>,
    resets_in: Option<TimeDelta>,
    is_reset: bool,
) -> Limit {
    let mut limit = Limit::new(
        "Claude Code",
        LimitKind::Session,
        "Session",
        percent,
        resets_in.map(|resets_in| now() + resets_in),
        now(),
        is_reset,
    );
    limit.window = window;
    limit
}

fn status(kind: StatusKind, text: &str) -> Option<LimitStatus> {
    Some(LimitStatus {
        kind,
        text: text.to_string(),
    })
}

fn for_limit(limit: &Limit) -> Option<LimitStatus> {
    limit_status::for_limit(limit, now(), &Zone::utc(), &en_us(), PaceDays::EveryDay)
}

fn kind_of(limit: &Limit) -> StatusKind {
    for_limit(limit).unwrap().kind
}

#[test]
fn on_track() {
    let s = for_limit(&make(
        27.0,
        Some(five()),
        Some(TimeDelta::minutes(191)),
        false,
    ))
    .unwrap();
    assert_eq!(s.kind, StatusKind::OnTrack);
    assert_eq!(s.text, "On track");
}

