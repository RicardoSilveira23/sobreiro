fn weekly(percent: f64, resets: &str, observed: &str) -> Limit {
    let mut limit = Limit::new(
        "Claude Code",
        LimitKind::Weekly,
        "Weekly",
        percent,
        Some(time(resets)),
        time(observed),
        false,
    );
    limit.window = Some(TimeDelta::days(7));
    limit
}

fn at(limit: &Limit, now: &str, days: PaceDays) -> LimitStatus {
    limit_status::for_limit(limit, time(now), &Zone::utc(), &en_us(), days).unwrap()
}

#[test]
fn weekdays_turn_a_midweek_alarm_into_on_track() {
    let l = weekly(58.0, "2026-11-16T09:00:00Z", "2026-11-12T09:00:00Z");
    let now = "2026-11-12T09:00:00Z";
    assert_eq!(at(&l, now, PaceDays::EveryDay).kind, StatusKind::Ends);
    assert_eq!(at(&l, now, PaceDays::Weekdays).text, "On track");
}

#[test]
fn weekdays_show_a_run_out_on_a_working_day() {
    // Reset Fri 09:00, read Mon 09:00 at 40%: 24 weekday hours gone, 36 more to run out.
    let l = weekly(40.0, "2026-11-13T09:00:00Z", "2026-11-09T09:00:00Z");
    let now = "2026-11-09T09:00:00Z";
    assert_eq!(at(&l, now, PaceDays::EveryDay).text, "On track");
    assert_eq!(at(&l, now, PaceDays::Weekdays).text, "Ends Tue 9:00 PM");
}

#[test]
fn a_stale_reading_past_its_weekday_run_out_is_likely_used_up() {
    let l = weekly(40.0, "2026-11-13T09:00:00Z", "2026-11-09T09:00:00Z");
    assert_eq!(
        at(&l, "2026-11-12T09:00:00Z", PaceDays::Weekdays).text,
        "Likely used up"
    );
}

#[test]
fn badge_colour_values() {
    // Whether the theme is dark, the kind of status, and the fill and the text of its badge.
    let rows = [
        (true, StatusKind::OnTrack, "#1A7F37", "#FFFFFF"),
        (false, StatusKind::OnTrack, "#1A7F37", "#FFFFFF"),
        (true, StatusKind::Ends, "#FFB020", "#0B0B0B"),
        (false, StatusKind::Ends, "#A35F00", "#FFFFFF"),
        (true, StatusKind::UsedUp, "#FF6B6B", "#0B0B0B"),
        (false, StatusKind::UsedUp, "#C4262E", "#FFFFFF"),
        (true, StatusKind::NotUsedYet, "#262626", "#F4F4F4"),
        (true, StatusKind::TooEarly, "#262626", "#F4F4F4"),
        (true, StatusKind::Resetting, "#262626", "#F4F4F4"),
        (false, StatusKind::NotUsedYet, "#E4E4E4", "#0D0D0D"),
        (false, StatusKind::TooEarly, "#E4E4E4", "#0D0D0D"),
        (false, StatusKind::Resetting, "#E4E4E4", "#0D0D0D"),
    ];
    for (dark, kind, fill, text) in rows {
        let badge = NightPalette::for_dark(dark).badge(kind);
        assert_eq!(badge.fill.to_hex(), fill, "{kind:?} dark={dark}");
        assert_eq!(badge.text.to_hex(), text, "{kind:?} dark={dark}");
    }
}

#[test]
fn badge_text_on_fill_is_readable_in_both_palettes() {
    for dark in [true, false] {
        for kind in [
            StatusKind::OnTrack,
            StatusKind::Ends,
            StatusKind::UsedUp,
            StatusKind::NotUsedYet,
            StatusKind::TooEarly,
            StatusKind::Resetting,
        ] {
            let badge = NightPalette::for_dark(dark).badge(kind);
            assert!(
                contrast::ratio(badge.text, badge.fill) >= 4.5,
                "{kind:?} dark={dark}"
            );
        }
    }
}

