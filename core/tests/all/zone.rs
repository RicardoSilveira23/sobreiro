//! `Zone` has no C# test file behind it: 1.x asked `TimeZoneInfo`. The rows are what the C#
//! got from `TimeZoneInfo` for the zones in `main.rs`, over the changes it printed for them.
use chrono::NaiveDateTime;
use sobreiro_core::display::{Zone, ZoneChange};

use crate::{ORACLE_ZONES, east, oracle_zone, time};

fn local(text: &str) -> NaiveDateTime {
    NaiveDateTime::parse_from_str(text, "%Y-%m-%dT%H:%M:%S").unwrap()
}

#[test]
fn utc_has_no_offset_and_no_change() {
    let zone = Zone::utc();
    assert_eq!(zone, Zone::fixed(east(0)));
    let moment = time("2026-11-09T12:34:56Z");
    assert_eq!(zone.offset_at(moment), east(0));
    assert_eq!(zone.local(moment), local("2026-11-09T12:34:56"));
    assert_eq!(zone.moment(local("2026-11-09T12:34:56")), Some(moment));
}

#[test]
fn a_change_holds_from_its_moment_on() {
    let at = time("2026-03-29T01:00:00Z");
    let zone = Zone::new(
        east(0),
        vec![ZoneChange {
            at,
            offset: east(3600),
        }],
    );
    assert_eq!(zone.offset_at(at - chrono::TimeDelta::seconds(1)), east(0));
    assert_eq!(zone.offset_at(at), east(3600));
    assert_eq!(
        zone.offset_at(at + chrono::TimeDelta::days(900)),
        east(3600)
    );
}

#[test]
fn changes_are_sorted_by_their_moment() {
    let first = ZoneChange {
        at: time("2026-03-29T01:00:00Z"),
        offset: east(3600),
    };
    let second = ZoneChange {
        at: time("2026-10-25T01:00:00Z"),
        offset: east(0),
    };
    assert_eq!(
        Zone::new(east(0), vec![second, first]),
        Zone::new(east(0), vec![first, second])
    );
}

#[test]
fn the_rows_name_zones_the_helper_knows() {
    for name in ORACLE_ZONES {
        let _ = oracle_zone(name);
    }
}

